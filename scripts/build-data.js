#!/usr/bin/env node
/* Wraps data/*.json as data/*.js (window.PREREQFLOW_DEFAULT = …) so the page can
 * load the built-in program maps with a plain <script> tag, which also works
 * when index.html is opened straight from disk (file://), where fetch() is blocked.
 *
 *   node scripts/build-data.js            regenerate
 *   node scripts/build-data.js --check    fail if the .js is out of date
 */
"use strict";
const fs = require("fs");
const path = require("path");

const SRC = path.join(__dirname, "..", "data", "ontario-tech-engineering-2026-2027.json");
const OUT = SRC.replace(/\.json$/, ".js");

const data = JSON.parse(fs.readFileSync(SRC, "utf8"));
if (data.format !== "prereqflow" || !Array.isArray(data.courses) || !Array.isArray(data.programs)) {
  console.error(`${path.basename(SRC)} is not a PrereqFlow export (format/courses/programs missing)`);
  process.exit(1);
}
const js = `/* Generated by scripts/build-data.js from ${path.basename(SRC)}. Do not edit by hand. */\n`
  + `window.PREREQFLOW_DEFAULT = ${JSON.stringify(data)};\n`;

if (process.argv.includes("--check")) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (cur !== js) { console.error(`${path.basename(OUT)} is out of date: run node scripts/build-data.js`); process.exit(1); }
  console.log(`${path.basename(OUT)} is up to date (${data.courses.length} courses, ${data.programs.length} programs)`);
} else {
  fs.writeFileSync(OUT, js);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${data.courses.length} courses, ${data.programs.length} programs)`);
}
