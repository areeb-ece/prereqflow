#!/usr/bin/env node
/* Copies the parts of the shared design system that PrereqFlow uses into css/fallback.css:
 * the night and paper themes and the shared scales from tokens.css, and the sd- components
 * from ui.css. The page loads that copy before /design/, so the live files win whenever they
 * load; the copy only matters offline (from disk) or while the live /design/ is older than
 * the one this page was built against. The master lives in the portfolio repo
 * (areeb-ece.github.io/public/design/), next to this one.
 *
 *   node scripts/sync-design.js            regenerate
 *   node scripts/sync-design.js --check    fail if the copy differs from the master
 *   DESIGN_DIR=path/to/design …            use another copy of the master
 */
"use strict";
const fs = require("fs");
const path = require("path");

const DIR = path.resolve(process.env.DESIGN_DIR || path.join(__dirname, "..", "..", "areeb-ece.github.io", "public", "design"));
const OUT = path.join(__dirname, "..", "css", "fallback.css");

if (!fs.existsSync(path.join(DIR, "tokens.css"))) {
  console.error(`No master design files at ${DIR}. Check out areeb-ece.github.io next to this repo, or set DESIGN_DIR.`);
  process.exit(process.argv.includes("--check") ? 0 : 1); // nothing to compare against is not a failure
}
const tokens = fs.readFileSync(path.join(DIR, "tokens.css"), "utf8");
const ui = fs.readFileSync(path.join(DIR, "ui.css"), "utf8");

// one theme block, from its selector to the closing brace; the markers that say "the master
// loaded" (--master, --theme-label) are left out, so the page can still tell the copy apart
function theme(name) {
  const sel = name === "dark" ? ':root, [data-theme="dark"] {' : `:root[data-theme="${name}"], [data-theme="${name}"] {`;
  const i = tokens.indexOf(sel);
  if (i < 0) throw new Error(`theme ${name} not found in tokens.css`);
  return tokens.slice(i, tokens.indexOf("\n}", i) + 2).split("\n").filter(l => !/--master:|--theme-label:/.test(l)).join("\n");
}
function from(text, marker, what) {
  const i = text.indexOf(marker);
  if (i < 0) throw new Error(`"${marker}" not found in ${what}`);
  return text.slice(text.lastIndexOf("/*", i)).trim();
}

const css = [
  "/* Generated by scripts/sync-design.js from the shared design system (areeb-ece.github.io/design/).",
  "   Do not edit by hand: change the master, then run `npm run sync:design`. The page loads this",
  "   before /design/, so the live files override it; it only shows offline or against an older",
  "   /design/. */",
  "",
  theme("dark"),
  "",
  theme("light"),
  "",
  from(tokens, "SHARED SCALES", "tokens.css"),
  "",
  "/* Offline there is no /design/theme.js to set data-scheme, so paper takes the light mixes itself. */",
  ':root[data-theme="light"] { --field-line: color-mix(in srgb, var(--ink) 60%, var(--sheet)); --well: color-mix(in srgb, var(--ink) 5%, var(--sheet)); }',
  "",
  "/* The text face, from this repo's own copy; online /design/fonts.css declares it again and wins. */",
  '@font-face { font-family: "Libre Franklin"; src: url("../assets/fonts/LibreFranklin-Var.woff2") format("woff2"); font-weight: 400 800; font-style: normal; font-display: swap; }',
  "",
  from(ui, "═══ Components", "ui.css"),
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (cur !== css) { console.error("css/fallback.css differs from the master design files: run npm run sync:design"); process.exit(1); }
  console.log("css/fallback.css matches the master design files");
} else {
  fs.writeFileSync(OUT, css);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} from ${DIR}`);
}
